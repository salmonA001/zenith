/// The columns a glyph really uses: (first, width). Text is spaced by what each letter needs.
pub fn extent(glyph: &[u8; GLYPH_H]) -> (usize, usize) {
    let all = glyph.iter().fold(0u8, |a, &r| a | r);
    if all == 0 {
        return (0, 3);
    }
    let first = (0..5).find(|c| all & (0x10 >> c) != 0).unwrap_or(0);
    let last = (0..5).rev().find(|c| all & (0x10 >> c) != 0).unwrap_or(4);
    (first, last - first + 1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_printable_character_except_space_has_ink() {
        for (i, g) in GLYPHS.iter().enumerate().skip(1) {
            assert!(g.iter().any(|&r| r != 0), "{:?} is blank", (FIRST + i as u8) as char);
            assert!(g.iter().all(|&r| r < 32), "{:?} is wider than five columns", (FIRST + i as u8) as char);
        }
    }

    #[test]
    fn narrow_letters_are_narrow() {
        assert_eq!(extent(&GLYPHS[(b'i' - FIRST) as usize]).1, 3);
        assert_eq!(extent(&GLYPHS[(b'W' - FIRST) as usize]).1, 5);
        assert_eq!(extent(&GLYPHS[0]), (0, 3));
    }
}
